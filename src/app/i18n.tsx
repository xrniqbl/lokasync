/* ── Flattened key type ────────────────────────────────────────────────────── */

type DictShape = typeof DICT;
export type DictPath =
  | `${keyof DictShape & string}.${keyof (DictShape["common"]) & string}`
  | `${keyof DictShape & string}.${keyof (DictShape["sidebar"]) & string}`
  | `${keyof DictShape & string}.${keyof (DictShape["settings"]) & string}`
  | `${keyof DictShape & string}.${keyof (DictShape["analytics"]) & string}`;

/* ── Translation helper ────────────────────────────────────────────────────── */

export function t(path: DictPath, lang: Lang): string {
  const [section, key] = path.split(".") as [keyof DictShape, string];
  const entry = (DICT[section] as Record<string, { en: string; id: string }>)[key];
  return entry?.[lang] ?? entry?.["en"] ?? path;
}

/* ── Lang Context ──────────────────────────────────────────────────────────── */

interface LangContextValue {
  lang: Lang;
  setLang: (lang: Lang) => void;
  t: (path: DictPath) => string;
}

const LangContext = createContext<LangContextValue>({
  lang: "id",
  setLang: () => {},
  t: (path) => path,
});

export function useLang() {
  return useContext(LangContext);
}

export function LangProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>(detectLang);

  const setLang = useCallback((next: Lang) => {
    setLangState(next);
    persistLang(next);
  }, []);

  const tBound = useCallback((path: DictPath) => t(path, lang), [lang]);

  /* notify the rest of the app when language changes */
  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);

  return (
    <LangContext.Provider value={{ lang, setLang, t: tBound }}>
      {children}
    </LangContext.Provider>
  );
}

/* ── Keep existing helpers backward-compatible ─────────────────────────────── */

export function detectLang(): Lang {
  try {
    const saved = localStorage.getItem("loka-lang");
    if (saved === "en" || saved === "id") return saved;
  } catch {
    /* storage unavailable */
  }
  return navigator.language?.toLowerCase().startsWith("id") ? "id" : "en";
}

export function persistLang(lang: Lang) {
  try {
    localStorage.setItem("loka-lang", lang);
  } catch {
    /* storage unavailable */
  }
}

/** EN / ID pill toggle. */
export function LangToggle({
  lang,
  onChange,
  className = "",
}: {
  lang: Lang;
  onChange: (lang: Lang) => void;
  className?: string;
}) {
  return (
    <div
      role="group"
      aria-label="Language"
      className={`flex items-center rounded-full border border-white/[0.08] bg-white/[0.04] p-0.5 ${className}`}
    >
      {(["en", "id"] as const).map((option) => (
        <button
          key={option}
          type="button"
          onClick={() => onChange(option)}
          aria-pressed={lang === option}
          className={`cursor-pointer rounded-full px-2.5 py-1 text-[11px] uppercase tracking-wide transition-colors ${
            lang === option
              ? "bg-neutral-50 text-neutral-900"
              : "text-neutral-400 hover:text-neutral-200"
          }`}
        >
          {option}
        </button>
      ))}
    </div>
  );
}
